# ---------------------------------------------------------------- numbers (checked)
W = (Fr(3), Fr(1))
ALPHA = Fr(1, 10)
DATA = [(Fr(2), Fr(4)), (Fr(-1), Fr(4))]
N = len(DATA)


def pred(w, x):
    return w[0] + w[1] * x


def J(w):
    return sum((pred(w, x) - y) ** 2 for x, y in DATA) / N


ERR = [pred(W, x) - y for x, y in DATA]
assert ERR == [1, -2] and [pred(W, x) for x, _ in DATA] == [5, 2]
K = -ALPHA * 2 / N                                   # −α·(2/n)
assert K == Fr(-1, 10)
PART0 = [K * e * 1 for e in ERR]
PART1 = [K * e * x for e, (x, _) in zip(ERR, DATA)]
assert PART0 == [Fr(-1, 10), Fr(2, 10)] and PART1 == [Fr(-2, 10), Fr(-2, 10)]
W_NEW = (W[0] + sum(PART0), W[1] + sum(PART1))
assert W_NEW == (Fr(31, 10), Fr(6, 10))
# the same step from the analytic gradient of J = (1/n)Σ(ŷ − y)²: dJ/dw0 = (2/n)Σe, dJ/dw1 = (2/n)Σe·x
g0 = Fr(2, N) * sum(ERR)
g1 = Fr(2, N) * sum(e * x for e, (x, _) in zip(ERR, DATA))
assert (W[0] - ALPHA * g0, W[1] - ALPHA * g1) == W_NEW and g1 == 4
assert J(W) == Fr(5, 2) and J(W_NEW) == Fr(117, 100) and J(W_NEW) < J(W)
# the slice J(w1) at w0 = 3 (drawn): 2.5·w1² − w1 + 1, slope 5·w1 − 1 = 4 at w1 = 1, minimum at 0.2
slice_ = lambda v: J((Fr(3), Fr(v)))
assert slice_(1) == Fr(5, 2) and slice_(Fr(1, 5)) == Fr(9, 10) and slice_(Fr(3, 5)) == Fr(13, 10)
assert all(slice_(Fr(k, 10)) >= slice_(Fr(1, 5)) for k in range(-10, 21))
# two one-line cases on the same model: an exact prediction, and x = 0
assert pred(W, 5) - 8 == 0                            # x = 5, y = 8: error 0 -> no change at all
e0 = pred(W, 0) - 1
assert e0 == 2 and K * e0 * 1 == Fr(-2, 10) and K * e0 * 0 == 0     # x = 0: w0 moves, w1 does not

# exam part (original): ŷ = 1 + 0.5x, x = 4, y = 6, α = 0.02, n = 1 -> the new prediction for the same example
QW, QA, QX, QY = (Fr(1), Fr(1, 2)), Fr(2, 100), 4, 6
qy = QW[0] + QW[1] * QX
qe = qy - QY
assert qy == 3 and qe == -3
d0, d1 = -QA * 2 * qe * 1, -QA * 2 * qe * QX
assert (d0, d1) == (Fr(12, 100), Fr(48, 100))
NW = (QW[0] + d0, QW[1] + d1)
assert NW == (Fr(112, 100), Fr(98, 100))
NEWY = NW[0] + NW[1] * QX
assert NEWY == Fr(504, 100) and abs(NEWY - QY) < abs(qy - QY)            # closer to y = 6
assert QW[0] + d0 + QW[1] * QX == Fr(312, 100)                           # only w0 updated
assert QW[0] + (QW[1] + d1) * QX == Fr(492, 100)                         # only w1 updated
assert (QW[0] - d0) + (QW[1] - d1) * QX == Fr(96, 100)                   # step in the wrong direction
