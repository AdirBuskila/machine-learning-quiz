# the order rule, checked on both examples and on random points
import random
rnd = random.Random(7)
for _ in range(2000):
    n = rnd.randint(1, 5)
    a = [rnd.uniform(-9, 9) for _ in range(n)]
    b = [rnd.uniform(-9, 9) for _ in range(n)]
    assert w.linf(a, b) <= w.l2(a, b) + 1e-12 <= w.l1(a, b) + 2e-12

