# ---------------------------------------------------------------- example 1: 1-D regression (verified)
X1 = [1, 3.5, 6, 8, 12]
Y1 = [10, 16, 22, 34, 50]
Q1 = 5
order, d1 = w.neighbours([(x,) for x in X1], (Q1,), 4, metric=w.l1)
assert [X1[i] for i in order] == [6, 3.5, 8, 1] and [d for d, _ in d1] == [1, 1.5, 3, 4, 7]
PRED1 = {k: sum(Y1[i] for i in order[:k]) / k for k in (1, 2, 3, 4)}
assert PRED1 == {1: 22, 2: 19, 3: 24, 4: 20.5}
for k, v in PRED1.items():
    assert np.isclose(KNeighborsRegressor(k).fit(np.array(X1).reshape(-1, 1), Y1).predict([[Q1]])[0], v)

# ---------------------------------------------------------------- example 2: the metric decides (verified)
A = [(3, 1), (6, 3), (6, 5)]
B = [(1, 1), (0, 5), (5, 4)]
TR, LB = A + B, ["A"] * 3 + ["B"] * 3
Q2 = (3, 3)
nm, dm = w.neighbours(TR, Q2, 3, metric=w.l1)
nc, dc = w.neighbours(TR, Q2, 3, metric=w.linf)
assert sorted(TR[i] for i in nm) == [(3, 1), (5, 4), (6, 3)] and [LB[i] for i in nm].count("A") == 2
assert [d for d, _ in dm] == [2, 3, 3, 4, 5, 5]
assert sorted(TR[i] for i in nc) == [(1, 1), (3, 1), (5, 4)] and [LB[i] for i in nc].count("B") == 2
assert [d for d, _ in dc] == [2, 2, 2, 3, 3, 3]
for metric, want in (("manhattan", "A"), ("chebyshev", "B")):
    assert KNeighborsClassifier(3, metric=metric).fit(np.array(TR), LB).predict([Q2])[0] == want

# ---------------------------------------------------------------- example 3: weighted average (verified)
DW, YW = [0.5, 1, 1], [10, 30, 50]
WW = [1 / d for d in DW]
NUM, DEN = sum(a * b for a, b in zip(WW, YW)), sum(WW)
assert (WW, NUM, DEN, NUM / DEN, sum(YW) / 3) == ([2, 1, 1], 100, 4, 25, 30)
# the same with scikit-learn: training points on a line at those distances from the query 0
XW = np.array([[0.5], [-1], [1], [3]])
assert np.isclose(KNeighborsRegressor(3, weights="distance").fit(XW, YW + [99]).predict([[0]])[0], 25)

