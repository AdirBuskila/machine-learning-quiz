# ---------------------------------------------------------------- lazy: the work per query (verified)
N_ROWS = 1_000_000
assert N_ROWS * 1 == 1_000_000            # one distance per stored row, for every single query

# ---------------------------------------------------------------- scaling (verified)
QC, C1, C2 = (1600, 5), (1650, 2), (1500, 5)
CC, SEATS = (1000, 3000), (2, 8)
mm = lambda p: ((p[0] - CC[0]) / (CC[1] - CC[0]), (p[1] - SEATS[0]) / (SEATS[1] - SEATS[0]))
raw1, raw2 = w.l2(QC, C1), w.l2(QC, C2)
sc1, sc2 = w.l2(mm(QC), mm(C1)), w.l2(mm(QC), mm(C2))
assert f"{raw1:.1f}" == "50.1" and raw2 == 100 and raw1 < raw2          # unscaled: C1 (2 seats!) is nearer
assert mm(QC) == (0.3, 0.5) and mm(C1) == (0.325, 0.0) and mm(C2) == (0.25, 0.5)
assert f"{sc1:.2f}" == "0.50" and math.isclose(sc2, 0.05) and sc2 < sc1  # scaled: C2 is nearer
assert 50 ** 2 == 2500 and 3 ** 2 == 9                                   # the cc term swallows the seats term

# ---------------------------------------------------------------- K (verified)
BL = [(1, 1), (2, 1.5), (1.5, 2.5), (2.5, 2.6), (2, 3.5), (3, 2)]
YL = [(5, 4), (6, 5), (5.5, 3), (6.5, 4), (2.6, 1.9)]                    # the last one: a noisy yellow inside blue
XK, LK = np.array(BL + YL), ["b"] * 6 + ["y"] * 5
QA, QB = (2.8, 1.6), (6, 4.4)
pred = lambda k, q: KNeighborsClassifier(k).fit(XK, LK).predict([q])[0]
assert pred(1, QA) == "y" and pred(3, QA) == "b"
assert pred(3, QB) == "y" and pred(11, QB) == "b" and LK.count("b") == 6 and LK.count("y") == 5
assert all(pred(11, (x, y)) == "b" for x in range(0, 8) for y in range(0, 6))   # K = n: one answer everywhere
n1, _ = w.neighbours(BL + YL, QA, 1)
assert (BL + YL)[n1[0]] == (2.6, 1.9)

# ---------------------------------------------------------------- one useless feature (verified)
QF, FA, FB = (5, 1), (5.2, 9), (8, 2)           # (useful feature, random feature); FA same class as the query
assert abs(QF[0] - FA[0]) < abs(QF[0] - FB[0])                       # by the useful feature alone: FA
dA, dB = w.l2(QF, FA), w.l2(QF, FB)
assert f"{dA:.2f}" == "8.00" and f"{dB:.2f}" == "3.16" and dB < dA      # with the noise feature: FB

